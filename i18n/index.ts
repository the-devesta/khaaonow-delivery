// Deep-merge the redesigned screens' strings (i18n/rider.ts) into each
// language without touching the legacy namespaces' existing keys.
const mergeDeep = (base: any, extra: any): any => {
  const out = { ...base };
  for (const [key, value] of Object.entries(extra)) {
    out[key] =
      value && typeof value === "object" && !Array.isArray(value)
        ? mergeDeep(base?.[key] ?? {}, value)
        : value;
  }
  return out;
};

const mergedResources = Object.fromEntries(
  Object.entries(resources).map(([lng, bundle]) => [
    lng,
    {
      translation: mergeDeep(
        (bundle as any).translation,
        (riderStrings as any)[lng] ?? riderStrings.en,
      ),
    },
  ]),
);

i18n.use(initReactI18next).init({
  compatibilityJSON: "v4",
  resources: mergedResources,
  lng: "en",
  fallbackLng: "en",
  interpolation: {
    escapeValue: false,
  },
});

export async function loadSavedLanguage() {
  const saved = await AsyncStorage.getItem(LANGUAGE_KEY);
  if (saved && LANGUAGES.some((language) => language.code === saved)) {
    await i18n.changeLanguage(saved);
  }
  return i18n.language as AppLanguage;
}

export async function setSavedLanguage(language: AppLanguage) {
  await AsyncStorage.setItem(LANGUAGE_KEY, language);
  await i18n.changeLanguage(language);
}

export function getLanguageLabel(language = i18n.language) {
  return (
    LANGUAGES.find((item) => item.code === language)?.nativeLabel ||
    LANGUAGES[0].nativeLabel
  );
}

export default i18n;
